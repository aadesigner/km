export function getPricingTestimonials(lang: string): Testimonial[] {
  return getTestimonials(lang).slice(0, 3);
}

export function shuffleTestimonials(items: Testimonial[], count = 3): Testimonial[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr.slice(0, count);
}
